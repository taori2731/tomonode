// Test-only browser response interception. Never bundled into the app.
const {spawn} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'artifacts','supporter-0512-qa');
const url=process.env.TOMONODE_SMOKE_URL || 'http://127.0.0.1:1427/';
let server,browser;
const assert=(ok,message)=>{if(!ok)throw Error(message);};
(async()=>{
  fs.mkdirSync(output,{recursive:true});
  if (!process.env.TOMONODE_SMOKE_URL) server=spawn(process.execPath,[path.join(root,'node_modules/vite/bin/vite.js'),'--port','1427','--host','127.0.0.1','--strictPort'],{cwd:root,stdio:'ignore',windowsHide:true});
  let ready=false; for(let i=0;i<60;i++){try{if((await fetch(url)).ok){ready=true;break;}}catch{} await new Promise(r=>setTimeout(r,250));} assert(ready,'local Vite failed');
  const executablePath=['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(p=>fs.existsSync(p));
  browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{localStorage.setItem('server-hub:language:v1','ja');localStorage.setItem('server-hub:theme:v1','light'); window.__QA_MEMBER={plan:'free',state:'free',registeredCount:3,serverLimit:3,expiresAt:null,paidUntil:null,cancelAtPeriodEnd:false,theme:null,previewOptIn:false,billingEnabled:false};});
  await page.route('**/src/lib/backend.ts*',async route=>{
    const response=await route.fetch(); const source=await response.text();
    await route.fulfill({response,body:source+`\nbackend.membershipStatus=async()=>({...window.__QA_MEMBER}); backend.membershipSetTheme=async(theme)=>{if(window.__QA_MEMBER.plan!=='supporter'&&theme)throw Error('Supporter required');window.__QA_MEMBER.theme=theme;return {...window.__QA_MEMBER};}; backend.membershipSetPreview=async(enabled)=>{window.__QA_MEMBER.previewOptIn=enabled;return {...window.__QA_MEMBER};};`});
  });
  await page.goto(url,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:'Survival World'}).waitFor();
  await page.locator('.titlebar .create').click();
  await page.getByRole('heading',{name:'Freeプランでは3個まで管理できます'}).waitFor();
  await page.screenshot({path:path.join(output,'free-limit-light.png')});
  await page.getByRole('button',{name:'応援プランを見る（受付準備中）'}).click();
  await page.getByRole('heading',{name:'Supporter限定テーマ'}).waitFor();
  assert(await page.getByRole('button',{name:'Supporter限定',exact:true}).count()===3,'three free previews');
  for(const button of await page.getByRole('button',{name:'Supporter限定',exact:true}).all())assert(await button.isDisabled(),'free theme gate');
  assert(await page.getByRole('button',{name:'本番受付は準備中',exact:true}).isDisabled(),'production checkout gate');
  await page.screenshot({path:path.join(output,'plan-free-light.png')});
  await page.evaluate(()=>{Object.assign(window.__QA_MEMBER,{plan:'supporter',state:'verified',expiresAt:Date.now()+86400000,paidUntil:Date.now()+172800000,serverLimit:null,cancelAtPeriodEnd:true});window.dispatchEvent(new Event('tomonode:membership-changed'));});
  await page.getByRole('button',{name:'会員状態を再確認'}).click();
  await page.getByRole('button',{name:'適用する',exact:true}).first().waitFor();
  const evidence=[];
  const contrast=(foreground,background)=>{
    const luminance=color=>{const rgb=color.match(/[\d.]+/g).slice(0,3).map(Number).map(v=>{v/=255;return v<=0.04045?v/12.92:Math.pow((v+0.055)/1.055,2.4);});return rgb[0]*0.2126+rgb[1]*0.7152+rgb[2]*0.0722;};
    const a=luminance(foreground),b=luminance(background);return (Math.max(a,b)+0.05)/(Math.min(a,b)+0.05);
  };
  for(const [id,name] of [['midnight','Midnight Harbor'],['orchid','Quiet Orchid'],['ember','Ember Studio']]){
    const card=page.locator('.member-theme-grid article').filter({hasText:name});
    await card.getByRole('button',{name:'適用する'}).click();
    await page.waitForFunction(theme=>document.querySelector('.app')?.dataset.memberTheme===theme,id);
    await page.locator('.settings-dialog-content').evaluate(el=>el.scrollTop=0);
    await page.screenshot({path:path.join(output,`theme-${id}.png`)});
    const theme=await page.locator('.app').evaluate(el=>({theme:el.dataset.memberTheme,bg:getComputedStyle(el).getPropertyValue('--bg'),text:getComputedStyle(el).getPropertyValue('--text')}));
    await page.getByRole('button',{name:'Discord運営通知を設定'}).click();
    const input=page.locator('input[type="password"]');
    await input.focus();
    const colors=await input.evaluate(el=>{const s=getComputedStyle(el);return {text:s.color,background:s.backgroundColor,outline:s.outlineColor,outlineStyle:s.outlineStyle,outlineWidth:s.outlineWidth,border:s.borderColor};});
    const ratio=contrast(colors.text,colors.background);
    assert(ratio>=4.5,`${id} input contrast ${ratio}`);
    assert(colors.outlineStyle!=='none'&&parseFloat(colors.outlineWidth)>0,`${id} input focus indicator`);
    await page.screenshot({path:path.join(output,`theme-${id}-input.png`)});
    evidence.push({...theme,input:colors,inputContrast:ratio});
    await page.getByRole('button',{name:'プランに戻る'}).click();
  }
  await page.getByRole('button',{name:'標準テーマに戻す'}).click();
  await page.waitForFunction(()=>!document.querySelector('.app')?.dataset.memberTheme);
  assert(await page.locator('.app').getAttribute('data-theme')==='light','restore previous standard theme');
  assert(await page.evaluate(()=>localStorage.getItem('server-hub:theme:v1'))==='light','preserve standard preference');
  await page.getByRole('button',{name:'Discord運営通知を設定'}).click();
  await page.getByRole('heading',{name:'Discord運営通知',exact:true}).waitFor();
  await page.screenshot({path:path.join(output,'discord-settings-light.png')});
  await page.evaluate(()=>{Object.assign(window.__QA_MEMBER,{plan:'free',state:'signed_out',theme:null});window.dispatchEvent(new Event('tomonode:membership-changed'));});
  await page.waitForFunction(()=>document.querySelector('input[type="password"]')?.disabled===true);
  assert(await page.getByRole('button',{name:'テスト通知を送信'}).isDisabled(),'logout sends no notification');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'discord-mobile.png')});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth); assert(!overflow,'mobile horizontal overflow');
  const contentWidth=await page.locator('.settings-dialog-content').evaluate(el=>el.getBoundingClientRect().width);
  assert(contentWidth>=300,'mobile settings content too narrow');
  assert(errors.length===0,errors.join('\n'));
  fs.writeFileSync(path.join(output,'ui-evidence.json'),JSON.stringify({mode:'headless browser + test-only membership responses; no native acceptance or real Discord',screens:10,themes:evidence,errors,mobileOverflow:overflow,mobileContentWidth:contentWidth},null,2));
  console.log('Supporter UI smoke PASS: limit, previews, themes, standard restoration, logout gate, mobile; no external send');
})().catch(error=>{console.error(error.message);process.exitCode=1;}).finally(async()=>{await browser?.close();server?.kill();});
